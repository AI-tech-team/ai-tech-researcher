/**
 * Markdown の**行の種類**を判定する規則を1か所に置く。
 *
 * ⚠ なぜ集約するか（2026-09-15 に同じ型のバグを2件続けて引いた）:
 * 同じ判定が3本にコピーされていて、そのうち1本だけ古い、という壊れ方が繰り返し出ている。
 *   - リンクの安全化（`safeHttpUrl` 相当）が3本 → エンティティ解除が2本に効かなかった（㊲）
 *   - 箇条書きの判定が3本 → メールだけ `^- ` のままで、**送った全メールに素の `*` が出ていた**（㊳）
 * 描画そのもの（React要素 / HTML文字列 / インラインstyle付きHTML）は用途ごとに違ってよいが、
 * 「この行は箇条書きか」という**文法の判定は1本**にする。
 */

/**
 * 箇条書きの行。LLMは `*   ` を好んで出すので `-` だけを見てはいけない。
 * 行頭の空白も許す（5月の号は `    * **実践的ヒント:** …` と字下げした入れ子を出していた）。
 * 上限を6文字にしてあるのは、深く字下げした塊まで吸い込まないため。
 * ⚠ `/g` を付けない。`.test()` と `.replace()` の両方で使うので、状態を持たせない。
 */
export const BULLET_LINE = /^[ \t]{0,6}[-*+][ \t]+(.+)$/;

/** 水平線。記号の後に何も無い行だけ（`- ` の箇条書きと衝突しない）。 */
export const HR_LINE = /^(?:-{3,}|\*{3,}|_{3,}|={3,})$/;

/** 箇条書きなら中身を返す。違えば null。 */
export function bulletContent(line: string): string | null {
  return line.match(BULLET_LINE)?.[1] ?? null;
}
